import type { Block, BlockItem, Workout } from '../types'

/** Atajo para escribir los ítems de un bloque. */
function it(
  exerciseId: string,
  prescription: string,
  extra: Omit<BlockItem, 'exerciseId' | 'prescription'> = {},
): BlockItem {
  return { exerciseId, prescription, ...extra }
}

type RawBlock = Omit<Block, 'id'>

/** Construye una rutina asignando ids estables a cada bloque. */
function wk(w: Omit<Workout, 'blocks'> & { blocks: RawBlock[] }): Workout {
  return {
    ...w,
    blocks: w.blocks.map((b, i) => ({ ...b, id: `${w.id}-b${i + 1}` })),
  }
}

